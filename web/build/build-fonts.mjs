// web/build/build-fonts.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ttf2woff2 from 'wawoff2'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(__dirname, '../../swiftui/Sources/Lemonade/Resources/Fonts')
const OUT_DIR = join(__dirname, '../dist/fonts')
const STYLES_DIR = join(__dirname, '../styles')

// Only the three weights the native platforms ship. --lmnd-font-weight-bold is 700,
// which is what SwiftUI already maps to SemiBold internally. The SemiBold face
// declares the range 600 700 so a 700 request resolves to this real face instead of
// the browser applying synthetic bold on top of the 600 face.
const WEIGHTS = [
  { file: 'Figtree-Regular.ttf', weight: '400' },
  { file: 'Figtree-Medium.ttf', weight: '500' },
  { file: 'Figtree-SemiBold.ttf', weight: '600 700' },
]

await mkdir(OUT_DIR, { recursive: true })
await mkdir(STYLES_DIR, { recursive: true })

const faces = []
for (const { file, weight } of WEIGHTS) {
  const ttf = await readFile(join(SOURCE, file))
  const woff2 = await ttf2woff2.compress(ttf)
  const outName = file.replace(/\.ttf$/, '.woff2')
  await writeFile(join(OUT_DIR, outName), woff2)
  const saved = Math.round((1 - woff2.length / ttf.length) * 100)
  console.log(`✓ ${outName} (${saved}% smaller)`)
  faces.push(`@font-face {
  font-family: 'Figtree';
  src: url('../dist/fonts/${outName}') format('woff2');
  font-weight: ${weight};
  font-style: normal;
  font-display: swap;
}`)
}

await writeFile(
  join(STYLES_DIR, 'fonts.css'),
  `/* Generated by web/build/build-fonts.mjs — do not edit. */\n\n${faces.join('\n\n')}\n`,
)
console.log('✓ styles/fonts.css written')
