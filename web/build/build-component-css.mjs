// web/build/build-component-css.mjs
//
// Build output only. Everything this writes lands in dist/, which is gitignored. The
// component stylesheets it reads are hand-written sources under src/; the committed
// bundle that includes them is web/styles/lemonade.css, written by the Kotlin
// web-css-bundle converter.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const COMPONENTS = join(__dirname, '../src/components')
const OUT = join(__dirname, '../dist/components.css')

async function stylesheets(dir) {
  const found = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) found.push(...(await stylesheets(path)))
    else if (entry.name.endsWith('.css')) found.push(path)
  }
  // Sorted, so the output is the same on every machine and in every checkout.
  return found.sort()
}

const paths = await stylesheets(COMPONENTS)
const parts = await Promise.all(
  paths.map(async (path) => `/* ${relative(COMPONENTS, path)} */\n${(await readFile(path, 'utf8')).trim()}`),
)

await mkdir(dirname(OUT), { recursive: true })
await writeFile(OUT, `/* Generated by web/build/build-component-css.mjs — do not edit. */\n\n${parts.join('\n\n')}\n`)
console.log(`✓ dist/components.css written (${paths.length} stylesheet${paths.length === 1 ? '' : 's'})`)
